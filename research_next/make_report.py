"""Generate reports/REPORT.md from reports/summary.csv + sensitivity_B.csv."""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
REP = ROOT / "reports"
s = pd.read_csv(REP / "summary.csv")
sens = pd.read_csv(REP / "sensitivity_B.csv") if (REP / "sensitivity_B.csv").exists() else None

L = []
A = L.append
A("# research_next — Automated Crypto Income Study ($1,000 total capital)\n")
A("Generated by `run_all.py` + `make_report.py`. All rules frozen before runs; "
  "no parameter tuning after seeing results. Cost stress = fee+slippage "
  "multiplier 1.0 / 1.5 / 2.0 on the 0.15%/side base.\n")

A("\n## 1. Data & sources\n")
A("- Spot: OKX USDT spot 1D candles, 12 majors, 2019-01 -> 2026-11-25 "
  "(`data/spot/`, fetched by slow_study/fetch_data.py).\n")
A("- Perp funding: Binance USD-M `fundingRate` full history per symbol "
  "(`data/fetch_binance_funding.py`). OKX public funding history only serves "
  "~3 months, so Binance is used; venue funding rates are correlated but NOT "
  "identical — documented approximation.\n")
A("- Quarterly futures: Binance USD-M delivery klines "
  "(`data/fetch_quarterly_futures.py`). BTC contracts from ~2020, ETH from "
  "2021-02 (ETH quarterly launched later — ETH B results start 2021).\n")
A("- Limitations: perp marked at spot price (no alt perp OHLC history); "
  "funding marked at daily close; USD vs USDT basis ignored; liquidation "
  "checked on daily HIGH only (intraday path unknown); cross-venue basis "
  "(OKX spot vs Binance perp/futures) ignored.\n")

A("\n## 2. Headline results (FULL period, cost_mult=1.0)\n")
A("| strategy | final $ | CAGR | mean/mo | geo/mo | worst/mo | maxDD | %mo>=6% | liq | max util | min liq dist |")
A("|---|---|---|---|---|---|---|---|---|---|---|")
for _, r in s[(s.split == "FULL") & (s.cost_mult == 1.0)].iterrows():
    A(f"| {r['strategy']} | {r['final']:.0f} | {r['cagr']*100:.1f}% | "
      f"{r['mean_mo']*100:.2f}% | {r['geo_mo']*100:.2f}% | {r['worst_mo']*100:.1f}% | "
      f"{r['maxDD']*100:.1f}% | {r['pct_ge6']*100:.0f}% | {int(r['n_liq'])} | "
      f"{r['max_util']:.2f} | {r['min_liq_dist_pct']:.1f}% |" if r['min_liq_dist_pct']==r['min_liq_dist_pct'] else
      f"| {r['strategy']} | {r['final']:.0f} | {r['cagr']*100:.1f}% | "
      f"{r['mean_mo']*100:.2f}% | {r['geo_mo']*100:.2f}% | {r['worst_mo']*100:.1f}% | "
      f"{r['maxDD']*100:.1f}% | {r['pct_ge6']*100:.0f}% | {int(r['n_liq'])} | "
      f"{r['max_util']:.2f} | n/a |")

A("\nBenchmarks: S5 1x = $1,434 (5.4% CAGR, 0.44%/mo, maxDD -0.9%, min liq dist 47.3%). "
  "BTC buy&hold = $3,615 (38.6% CAGR, maxDD -53%). Stablecoin ~3.5%/yr ≈ 0.29%/mo. Cash = 0.\n")

A("\n## 3. Cost stress (FULL, final equity)\n")
A("| strategy | 1.0x | 1.5x | 2.0x |")
A("|---|---|---|---|")
for strat, g in s[(s.split == "FULL") & (~s.strategy.str.startswith("BENCH"))].groupby("strategy"):
    g = g.set_index("cost_mult")
    if not all(cm in g.index for cm in (1.0, 1.5, 2.0)):
        continue
    A(f"| {strat} | {g.loc[1.0,'final']:.0f} | {g.loc[1.5,'final']:.0f} | {g.loc[2.0,'final']:.0f} |")

A("\n## 4. Period splits (cost_mult=1.0, mean monthly arithmetic)\n")
A("| strategy | FULL | 2023+ | 2025+ |")
A("|---|---|---|---|")
for strat, g in s[s.cost_mult == 1.0].groupby("strategy"):
    g = g.set_index("split")
    row = f"| {strat} |"
    for sp in ("FULL", "2023+", "2025+"):
        row += f" {g.loc[sp,'mean_mo']*100:.2f}% |" if sp in g.index else " n/a |"
    A(row)

A("\n## 5. Strategy A — multi-asset funding arb\n")
A("Top-3 trailing-30d funding, weekly rebalance, alloc 0.90/K, negative-funding "
  "avoidance. Result: **does NOT beat BTC-only S5 1x**. Alt funding is lower on "
  "average, selection churn costs $200-350 over the period (vs $26 for S5), and "
  "the 0.90 alloc cap dilutes carry. At 1.5x/2.0x cost stress it loses money. "
  "L=2 min liq distance 1.9% — fragile.\n")

A("\n## 6. Strategy B — cash-and-carry basis\n")
A("Long spot + short quarterly future, hold to expiry, roll if basis >3%/yr. "
  "ETH basis was large (entries at 5-20%/yr annualized). **Best raw returns** "
  "but 8-9 futures-liquidations per run: with IMR=20% the short future leg is "
  "effectively 5x-leveraged and ETH/BTC rallied >20% within quarters repeatedly. "
  "Each liquidation loses the margin account (~16% of deployed capital). "
  "Sensitivity (reports/sensitivity_B.csv): ETH stays profitable across "
  "IMR 10-35% and basis thresholds 2-5%; BTC is marginal. Higher IMR = fewer "
  "liquidations but lower return on capital.\n")

A("\n## 7. Strategy C — adaptive funding carry\n")
A("BTC carry with weekly exposure multiplier from trailing funding + 30d vol "
  "(frozen thresholds). L=1: $1,134 final, 0.26%/mo, maxDD -0.6%, min liq dist "
  "62%, zero liquidations, robust to 2x costs. **Positive and safe but BELOW "
  "S5 1x ($1,434)** — the exposure cuts (m=0.25/0.5 regimes) cost more carry "
  "than they save in risk, because S5 1x was never near liquidation anyway. "
  "L=2: $1,187, min liq dist 14% — not approved-leverage territory.\n")

A("\n## 8. Liquidation & capital-utilization analysis\n")
A("- A: 0 liquidations all configs; max util ~1.01-1.03 (reserve briefly "
  "negative-equivalent via margin top-ups — engine allows reserve floor 0).\n")
A("- B: 8 (BTC) / 9 (ETH) liquidations at IMR=20%; util ~1.00 while in market "
  "(fully deployed spot+margin).\n")
A("- C: 0 liquidations; util ~1.07-1.12 (L=2).\n")
A("- S5 1x benchmark: 0 liquidations, min liq dist 47.3%.\n")

A("\n## 9. Sensitivity\n")
A("- Costs: see §3 — A goes negative at 1.5x; B degrades ~7%/step; C barely "
  "moves (few trades).\n")
A("- B IMR/basis: see reports/sensitivity_B.csv — ETH robust, BTC marginal.\n")
A("- A/C rules were frozen pre-run; no post-hoc tuning performed.\n")

A("\n## 10. Ranking & recommendation\n")
A("1. **B_cashcarry_ETH** — highest net return (CAGR 13.6%, ~1.15%/mo mean, "
  "10.6% of months >=6%) but with 9 liquidation events and -13% maxDD. "
  "Deserves further testing ONLY with a safer margin structure (higher IMR, "
  "cross-margin with spot collateral, or smaller per-cycle allocation).\n")
A("2. **S5 1x (existing benchmark)** — $1,434, 0.44%/mo, maxDD -0.9%, 47% liq "
  "distance. Still the best risk-adjusted carry.\n")
A("3. **C_adaptive_L1** — $1,134, 0.26%/mo, safest (62% liq distance) but "
  "underperforms S5 1x; the adaptive overlay did not pay for itself.\n")
A("4. **A_funding_arb** — rejected: multi-asset selection destroyed value vs "
  "BTC-only after costs.\n")
A("5. BTC buy&hold — highest CAGR but -53% DD; not income, not comparable.\n")

A("\n## 11. Final answer\n")
A("**Given $1,000 total capital, the strongest empirically supported prospect "
  "of recurring monthly income is Strategy B cash-and-carry on ETH quarterly "
  "futures — IF the liquidation problem is fixed.** As modelled (IMR 20%, "
  "isolated margin) it earned ~1.15%/month mean with 10.6% of months >=6%, "
  "but suffered 9 liquidations and -13% maxDD; the edge is real (ETH basis "
  "premium) but the risk structure is not yet acceptable. The compromise "
  "required: run it at IMR >=35% (or cross-margin the spot leg as collateral), "
  "which cuts return on capital roughly in half but removes most liquidations "
  "(sensitivity: ETH IMR=35% still final $1,347 vs $1,652). If that compromise "
  "is unacceptable, **S5 1x remains the deployable answer**: ~0.44%/month, "
  "near-zero drawdown, 47% liquidation distance — modest but credible, and it "
  "is the only candidate that is both profitable after 2x costs and "
  "catastrophe-free in-sample. No strategy here reaches 6%/month sustainably.\n")

A("\n## 12. What could NOT be verified\n")
A("- Exact OKX/Bybit liquidation formulas, ADL, insurance-fund mechanics.\n")
A("- Binance delivery-futures tier IMR/MMR tables (assumed 20%/0.5%).\n")
A("- Lebanon account approval (not excluded by name, but discretionary; BDL "
  "Article 10 blocks bank funding rails — see execution/venue_notes.md).\n")
A("- Intraday liquidation paths (daily HIGH approximation only).\n")
A("- Point-in-time universe/liquidity (current top-12 majors, survivorship "
  "bias acknowledged).\n")

out = REP / "REPORT.md"
out.write_text("\n".join(L), encoding="utf-8")
print("wrote", out)
